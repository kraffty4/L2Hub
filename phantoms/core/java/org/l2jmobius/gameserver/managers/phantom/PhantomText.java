	/**
	 * @param text строка по-русски
	 * @return она же на языке сервера
	 */
	public static String tr(String text)
	{
		return "en".equals(L2HubWorldConfig.LANGUAGE) ? EN.getOrDefault(text, text) : text;
	}

	/**
	 * Имя спота на языке сервера: у тёзок в имени — сторона света по-русски («Ketra Orc Outpost · северо-восток», генератор {@code COMPASS} в {@code tools/fake_players.py}).
	 * @param name имя спота или места сбора
	 * @return оно же на языке сервера
	 */
	public static String spotName(String name)
	{
		if (!"en".equals(L2HubWorldConfig.LANGUAGE))
		{
			return name;
		}
		final int side = name.lastIndexOf(" · ");
		return side < 0 ? name : name.substring(0, side + 3) + SIDES.getOrDefault(name.substring(side + 3), name.substring(side + 3));
	}
