 static String choose(String input,String previous,Random random){return choose(input,null,previous,random);}
 static String choose(String input,String previousNpc,String previous,Random random){
  if(input==null)return null;
  String text=input.toLowerCase(Locale.ROOT).replace('ё','е').replaceAll("[^\\p{L}\\p{N}]+"," ").strip();
  String prior=previousNpc==null?"":previousNpc.toLowerCase(Locale.ROOT).replace('ё','е');
  String priorWords=prior.replaceAll("[^\\p{L}\\p{N}]+"," ").strip();
  if(priorWords.matches("(?s).*(?:как(?: у тебя)? дела|как жизнь|как оно|как сам|как сама|у тебя как|ты как|как ты)$")){
   if(text.matches("(?:(?:да|ну|вроде|да вроде) )?(?:норм|нормально|нормас|хорошо|потихоньку|помаленьку|все норм|все нормально|все ок|все окей)(?: (?:а )?(?:ты|ты как|у тебя|у тебя как|сам|сам как|сама|сама как))?")){
    List<String> answers=text.matches(".* (?:ты|ты как|у тебя|у тебя как|сам|сам как|сама|сама как)")?List.of("у меня тоже нормально)","да я тоже потихоньку","тоже всё норм"):
     List.of("ну и хорошо)","отлично","ну и отлично");
    return different(answers,previous,random);
   }
   if(text.matches("(?:не очень|так себе|плохо|не особо)"))return different(List.of("чё такое?","что случилось?","что-то произошло?"),previous,random);
  }
  String question=prior.replaceAll("[^\\p{L}\\p{N}]+"," ").strip().replaceAll("(?U)\\bкто нибудь\\b","ктонибудь");
  if(prior.contains("?")&&!Pattern.compile("(?U)\\b(?:где|когда|почему|как|кто|чей|сколько|какой|какая|какие|что|куда|откуда|зачем)\\b").matcher(question).find()){
   if(text.matches("(?:да|ага|угу|нет|неа)"))return different(List.of("ага","а, ясно","окей","понял"),previous,random);
   if(text.matches("(?:не знаю|хз|без понятия)"))return different(List.of("а, понятно","ясно, спасибо","ладно, спасибо"),previous,random);
  }
  for(Intent intent:INTENTS)if(intent.pattern().matcher(text).matches()){
   return different(intent.answers(),previous,random);
  }
  return null;
 }
 private static String different(List<String> answers,String previous,Random random){int start=random.nextInt(answers.size());for(int i=0;i<answers.size();i++){String answer=answers.get((start+i)%answers.size());if(!answer.equals(previous))return answer;}return null;}
